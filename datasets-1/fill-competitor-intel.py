def main():
    wb = openpyxl.load_workbook(PATH)
    ws = wb[SHEET]

    wrap = Alignment(vertical="top", wrap_text=True)
    cols = ["D", "E", "F", "G", "H", "I", "J", "K"]

    written = 0
    for row, values in ROWS.items():
        assert len(values) == len(cols), f"row {row}: {len(values)} values"
        for col, value in zip(cols, values):
            cell = ws[f"{col}{row}"]
            cell.value = value
            cell.alignment = wrap
        ws[f"M{row}"].value = SYNTH
        ws[f"M{row}"].alignment = wrap
        written += 1

    # Loud provenance banner directly above the metric table.
    banner = ws["A13"]
    banner.value = (
        "SYNTHETIC DATA NOTICE - All brand values in columns E-J below are illustrative "
        "placeholders generated for demo/POC use. They are NOT researched or sourced figures "
        "and must not be quoted externally or used for any real decision. Columns D "
        "(recommended visualization) and K (ingestion mechanism) are genuine recommendations. "
        "Replace E-J with licensed/verified data before any external use."
    )
    banner.font = Font(bold=True, color="9C0006")
    banner.fill = PatternFill("solid", fgColor="FFC7CE")
    banner.alignment = Alignment(vertical="top", wrap_text=True)
    ws.row_dimensions[13].height = 58
    ws.merge_cells("A13:M13")

    for col, width in {
        "D": 42, "E": 52, "F": 46, "G": 44, "H": 44, "I": 46, "J": 44, "K": 40, "M": 34,
    }.items():
        ws.column_dimensions[col].width = width

    wb.save(PATH)
    print(f"Wrote {written} metric rows x {len(cols)} columns + notes + banner -> {PATH}")


if __name__ == "__main__":
    main()
